#!/usr/bin/env node
/**
 * COF001: trace the Part 1A (gas) carry - the balance left once invoices are paid - over the whole ledger.
 *
 * Basis matches the v5 statements: gas amounts only (cylinder SKU lines excluded, mixed documents split
 * per data/db_sku_classification.json; 53619/15803/15804 split as assumed), quarantined payment 29492
 * excluded, lane overrides in config/lane_overrides.json applied (45528 S.1 treated as gas, ASSUMED). Each payment / credit note is paired with an unused gas invoice of the same amount; the
 * unpaired items, summed by date, are the carry without open-invoice timing.
 *
 * Usage: node analysis/debtors/COF001/scripts/trace_1a_carry.mjs
 * Output: analysis/debtors/COF001/reports/COF001_1A_Carry_Trace.md
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../../..');
const ACCT = path.join(ROOT, 'analysis/debtors/COF001');
const db = JSON.parse(fs.readFileSync(path.join(ACCT, 'data/db_sku_classification.json'), 'utf8'));
const quarantine = JSON.parse(fs.readFileSync(path.join(ACCT, 'config/quarantine.json'), 'utf8')).items;
const laneOverrides = JSON.parse(fs.readFileSync(path.join(ACCT, 'config/lane_overrides.json'), 'utf8')).items;
const cyl = new Set(db.cyl_docs.map((x) => x.replace(/^0+/, '')));
const mixed = new Map(db.mixed_docs.map((m) => [`${m.doc_no.replace(/^0+/, '')}|${m.entry_type}`, m]));
const ASSUMED_GAS = { '15803|Crd Note': -3002.83, '15804|Crd Note': 0, '53619|Invoice': 3002.83 };
const r2 = (n) => Math.round(n * 100) / 100;
const fmt = (n) => (Math.abs(n) < 0.005 ? 0 : n).toLocaleString('en-US', { minimumFractionDigits: 2, maximumFractionDigits: 2 });

const rows = [];
for (const line of fs.readFileSync(path.join(ACCT, 'raw/COF001_COMBINED.TXT'), 'utf8').split('\n')) {
  const p = [...line.matchAll(/"([^"]*)"/g)].map((m) => m[1]);
  if (p.length < 11 || !/^\d+$/.test(p[0]) || p[6] === 'BALANCE B/F:') continue;
  const iso = p[4].split('/').reverse().join('-');
  const doc = p[2].replace(/^0+/, '');
  const type = p[3];
  const amount = Number(p[9]);
  if (quarantine.some((q) => String(q.doc_no) === doc && q.entry_type === type && q.date === iso)) continue;
  let gas = amount;
  const key = `${doc}|${type}`;
  if (type === 'Invoice' || type === 'Crd Note') {
    if (key in ASSUMED_GAS) gas = ASSUMED_GAS[key];
    else if (mixed.has(key)) gas = mixed.get(key).gas_amt;
    else if (cyl.has(key)) gas = 0;
    for (const o of laneOverrides.filter((x) => `${x.doc_no}|${x.entry_type}` === key)) gas += o.toLane === 'LPG' ? o.amount : -o.amount;
  }
  if (Math.abs(gas) >= 0.005) rows.push({ iso, doc, type, amount: r2(gas) });
}
rows.sort(
  (a, b) => a.iso.localeCompare(b.iso) || (a.type === 'Crd Note') - (b.type === 'Crd Note') || a.doc.localeCompare(b.doc),
);

// Monthly low and close of the running 1A balance.
let run = 0;
const months = new Map();
for (const r of rows) {
  run = r2(run + r.amount);
  const m = r.iso.slice(0, 7);
  const e = months.get(m) || { low: Infinity, close: 0 };
  e.low = Math.min(e.low, run);
  e.close = run;
  months.set(m, e);
}

// Pair payments / credit notes with same-amount gas invoices; the rest is the carry.
const debits = rows.filter((r) => r.amount > 0).map((r) => ({ ...r, used: false }));
const credits = rows.filter((r) => r.amount < 0).map((r) => ({ ...r, used: false }));
for (const c of credits) {
  const d = debits.find((x) => !x.used && Math.abs(x.amount + c.amount) < 0.025);
  if (d) {
    d.used = true;
    c.used = true;
  }
}
const unpaired = [...debits, ...credits].filter((x) => !x.used).sort((a, b) => a.iso.localeCompare(b.iso));
let cum = 0;
const timeline = unpaired.map((u) => ({ ...u, cum: (cum = r2(cum + u.amount)) }));
const total = r2(rows.reduce((s, r) => s + r.amount, 0));

const md = [];
md.push('# COF001 - Part 1A (gas) carry trace');
md.push('');
md.push('*Generated by `analysis/debtors/COF001/scripts/trace_1a_carry.mjs`; do not edit numbers by hand.*');
md.push('');
md.push('Basis: same as the v5 statements (gas amounts only, cylinder SKU lines excluded, quarantined payment 29492 excluded; 53619/15803/15804 split as assumed; lane overrides in `config/lane_overrides.json` applied, so invoice 45528\'s S.1 line counts as gas, ASSUMED pending ADM-152). Each payment or credit note is paired with an unused gas invoice of the same amount. The items left unpaired, summed by date, are the carry without open-invoice timing. Pairing by amount is a method, not the ERP allocation: ASSERTED.');
md.push('');
md.push(`Ledger total: R${fmt(total)}; carry from unpaired items: R${fmt(cum)}; the R${fmt(r2(total - cum))} difference is the ERP's 0.02 rounding on otherwise exact pairs.`);
md.push('');
md.push('## Unpaired items and cumulative carry');
md.push('');
md.push('| Date | Type | Doc | Amount (R) | Cumulative carry (R) |');
md.push('| :--- | :--- | :--- | ---: | ---: |');
for (const t of timeline) md.push(`| ${t.iso} | ${t.type} | ${t.doc} | ${fmt(t.amount)} | ${fmt(t.cum)} |`);
md.push('');
md.push('## Reading (ASSERTED, from the table above and the database)');
md.push('');
md.push('- **Mar 2022 to Dec 2024: carry at zero.** The only excursion (May to Aug 2023: overpayment 23445 against later short-paid invoices 22252 and 23258, settled by 23395) closed back to zero.');
md.push('- **30 Dec 2024: carry turns negative, R-1,258.64.** Payment 35877 (R9,649.56) exceeds the gas part of invoice 39311 (R8,390.92) by R1,258.64. The database records 35877 at R8,390.92, which suggests the excess was not allocated to any invoice (not confirmed in the ERP).');
md.push('- **Jan to Jul 2025: swings net back to about R-1,258.7.** Extra payments 36509, 36512 (31 Jan) and 38270 (15 Apr) are absorbed by gas invoices that received no same-amount payment (41238, 41562, 42614, 42875, and 43287 short-paid by 6,446.60).');
md.push('- **9 and 18 Aug 2025: no change.** With the lane override, invoice 45528 (R7,400.19) is all gas and payment 40757 pays it exactly. Without the override, its R6,037.50 S.1 line sits in Part 1B and this step would take the carry R6,037.50 further negative (see ADM-149 / ADM-152).');
md.push('- **17 Dec 2025: R-517.50 more.** Payment 42636 (R517.50, database reference 44730) pays the 9kg deposit that credit note 12956 left uncredited in Jul 2025, which also stays owed in Part 1B.');
md.push('- **11 Feb 2026: R+6,960.00.** Rental invoice 49204 is unpaid, giving the 5,183.8 carry seen on the 2026 statements (it would be -853.7 without the 45528 lane override).');
md.push('- **Net position.** The 42636 deposit payment (R517.50) mirrors R517.50 of the R1,368.50 Part 1B balance. What is left is the Dec 2024 overpayment (R1,258.64) less the R851.00 deposit balance carried in Part 1B since Aug 2023: about R407.6 in the customer\'s favour.');
md.push('');
md.push('## Monthly low and close of the 1A running balance (by document date)');
md.push('');
md.push('| Month | Low (R) | Close (R) |');
md.push('| :--- | ---: | ---: |');
for (const [m, e] of [...months].sort()) md.push(`| ${m} | ${fmt(r2(e.low))} | ${fmt(e.close)} |`);
md.push('');

fs.writeFileSync(path.join(ACCT, 'reports/COF001_1A_Carry_Trace.md'), md.join('\n'));
console.log(`total ${fmt(total)} | carry ${fmt(cum)} | unpaired ${unpaired.length} | wrote reports/COF001_1A_Carry_Trace.md`);
